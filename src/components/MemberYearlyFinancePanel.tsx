function stripAutoFeeFields(fee: MemberMonthlyFee | AutoGeneratedMemberFee): MemberMonthlyFee {
  const clone = { ...fee } as MemberMonthlyFee & Partial<AutoGeneratedMemberFee>;
  delete clone.isAutoGenerated;
  delete clone.yearNumber;
  delete clone.monthNumber;
  delete clone.classification;
  if (clone.id.startsWith('fee-auto-')) {
    const safeMemberId = (clone.memberId || 'm').replace(/[^a-zA-Z0-9_-]/g, '').slice(0, 18) || 'm';
    const ym = (clone.month || '').replace('-', '');
    clone.id = `fee-${safeMemberId}-${ym}-${Date.now().toString().slice(-4)}`;
  }
  return clone;
}

function upsertMemberFee(
  existingList: MemberMonthlyFee[],
  nextFee: MemberMonthlyFee | AutoGeneratedMemberFee
): MemberMonthlyFee[] {
  const materialized = stripAutoFeeFields(nextFee);
  const idx = existingList.findIndex(
    (f) =>
      f.id === nextFee.id ||
      f.id === materialized.id ||
      (f.memberId === materialized.memberId && f.month === materialized.month)
  );
  if (idx >= 0) {
    return existingList.map((f, i) => (i === idx ? materialized : f));
  }
  return [materialized, ...existingList];
}

function getSettlementLabel(status?: FeeSettlementStatus): string {
  switch (status) {
    case 'paid':
      return 'Pago';
    case 'forgiven':
      return 'Perdoado';
    case 'cancelled':
      return 'Cancelado';
    case 'written_off':
      return 'Baixado';
    case 'exempt':
      return 'Isento';
    default:
      return 'Pendente';
  }
}

